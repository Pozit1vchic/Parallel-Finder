"""Build the offline QML catalogs and reject missing translations."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[2]


def build():
    text = (ROOT / 'ui/qml/L10n.qml').read_text(encoding='utf-8-sig')
    english = json.loads(re.search(r'\ben:\s*(\{.*?\})\s*[,\n]', text, re.S)[1])
    catalogs = {lang: {} for lang in ('ky', 'kk', 'uk', 'tr')}
    aliases = {'ui.singleMoment': 'ui.432', 'ui.manualPair': 'ui.433'}
    for number, line in enumerate((ROOT / 'tools/localization/catalog.tsv').read_text(encoding='utf-8-sig').splitlines(), 1):
        if not line.strip():
            continue
        fields = line.split('|')
        if len(fields) != 5 or any(not value.strip() for value in fields):
            raise ValueError(f'Invalid catalog row {number}')
        canonical = fields[0].strip()
        key = aliases.get(canonical, canonical if canonical in english else fields[0])
        for lang, value in zip(catalogs, fields[1:]):
            phrase = english.get(key, key)
            # Keep separators used when labels are joined with counts/paths.
            leading = re.match(r'^\s*', phrase)[0]
            trailing = re.search(r'\s*$', phrase)[0]
            value = leading + value.strip() + trailing
            catalogs[lang][key] = value
            catalogs[lang][phrase] = value
    # Identical English phrases share one translation, including review keys.
    for lang, catalog in catalogs.items():
        for key, phrase in english.items():
            if key not in catalog and phrase in catalog:
                catalog[key] = catalog[phrase]
        missing = [key for key in english if key not in catalog]
        if missing:
            raise ValueError(f'{lang}: missing {missing}')
        inline = set()
        for qml in (ROOT / 'ui/qml').glob('*.qml'):
            inline.update(json.loads(value) for value in re.findall(
                r'L10n\.translate\(("(?:[^"\\]|\\.)*")', qml.read_text(encoding='utf-8-sig')))
        missing_inline = sorted(inline - catalog.keys())
        if missing_inline:
            raise ValueError(f'{lang}: missing inline phrases {missing_inline}')
    return '.pragma library\n// Generated by tools/localization/build_catalog.py; offline at runtime.\nvar dictionaries = ' + json.dumps(catalogs, ensure_ascii=False, indent=2) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = build()
    target = ROOT / 'ui/qml/Translations.js'
    if args.check:
        if target.read_text(encoding='utf-8-sig') != result:
            raise SystemExit('Generated translations are out of date')
    else:
        target.write_text(result, encoding='utf-8')
    print('Complete offline catalogs: ky, kk, uk, tr')
